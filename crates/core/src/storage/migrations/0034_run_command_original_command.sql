-- 决策 297（票 03 / 06）：命令台账加一列「改写之前的那一条」。
--
-- 语义：**只有真的发生过改写才写**；NULL = 按原样跑——「没启用 / 这一次调用点传了
-- `Rewrite::None` / rtk 不在场」这三件事对台账是同一件事。
--
-- 为什么两份都要记（三种记法里只有这个不丢信息）：只记实际执行的串 → 原串丢了，而原串
-- 是模型想要的东西；只记原串 → `cat X` 与 `rtk read X` 的输出不一样，排障会看错；
-- 记两行 → 混淆「跑了几条命令」这个计数。
--
-- 可空而不是 `NOT NULL DEFAULT ''`：空串是命令串的一个合法位置，拿它当哨兵会让
-- 「有没有改写过」在界面上说不清（迁移 0004「不采用哨兵值」的同一条）。
--
-- `command` 那一列的语义随之钉死为「**实际执行的**命令串（脱敏后）」——改写之前它同时
-- 充当两者，故这个区分在本次之前不存在。
ALTER TABLE kanban_node_commands ADD COLUMN original_command TEXT;
