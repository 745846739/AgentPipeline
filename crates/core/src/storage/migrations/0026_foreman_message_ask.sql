-- 决策 265：结构化选项提问（`.turn.ask`）——问题与选项挂在**那一轮的 assistant 行**上。
--
-- 为什么不新造表：票面口径「不新造表」对问题本身同样成立。问的话是值班长说出口的话，
-- 它的结构化载荷与 `content` 是同一件事的两个面：`content` 给模型与翻台账的人，
-- `ask_json` 给时间线渲染可点的选项。提议要平行表是因为它有 TTL / 一次一按 / 执行状态
-- 那套生命周期，而问题没有——失效判据就是「后到的 user 消息」（决策 265③），
-- 那是前端从消息序列里纯派生的，不需要行状态。
--
-- 形状写死在执行点（`tools.rs::ask` 校验后才落）：`{"question": …, "options": [2–4 句]}`，
-- 故这一列只会是这个形状或 NULL——界面拿它直接渲染，不二次解析正文。
--
-- 可空：绝大多数回话不带问题（与 `thinking` / `briefing_json` 同一条口径，不存空对象）。
ALTER TABLE kanban_foreman_messages ADD COLUMN ask_json TEXT;
