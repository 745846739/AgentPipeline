-- 对讲台信息流回看（.scratch/talk-replay 票 01）：消息行的**在途状态**。
--
-- 诉求是「重新进入对讲台，之前的信息流都在」——而正在说的那一半此前只走 SSE 广播、
-- 从不落库，SSE 又无回放，于是刷新 / 重启之后那半轮既不在库里也补不回来。修法是台账
-- **边流边写**：一轮开工就建这条回话的 assistant 半截行，收口时把它写成完整行。
--
-- 取值（`NULL` = 已收口的正常行，存量行全是这一类，不回填）：
--   'in_flight'    一轮正在跑，这一行是它当场建的半截行（票 01）
--   'interrupted'  进程被杀留下的半截行，由启动恢复标上（票 03）
--
-- **为什么是行上的一个字段而不是新表**：半截行就是那一轮的台账行本尊——收口时同一行
-- id 被写成完整行，「一次回话 = user 行 + assistant 行」的行数语义（决策 260 的形状）
-- 一点不变，改的只是中途是否可见。另起一张表等于给「一次回话」造出两个身份。
--
-- 这是对**决策 260「回话落库才算数」的显式修订**（spec .scratch/talk-replay 决策 13）：
-- 在途即落库、收口才算完整；`turn_in_flight` 那个进程内读数仍照旧回答「此刻有没有轮
-- 在跑」，两者分工不合并（spec 决策 7）。
ALTER TABLE kanban_foreman_messages ADD COLUMN status TEXT;

-- **行内位置序号**（票 02，快照与直播的拼接判据）：在途事件（对话增量 / 工具调用）
-- 带 `seq`，行上记「刷到哪了」——前端取快照记 `seq0`，只接 `seq > seq0` 的增量，
-- 于是刷新之后接缝处**不重不漏**。`seq` 只做去重：**不做回放**（事件仍旧只走广播，
-- 没到过的字靠下一次快照读回，决策 275 原样成立）。存量行恒为 0（从未有过在途事件）。
ALTER TABLE kanban_foreman_messages ADD COLUMN seq INTEGER NOT NULL DEFAULT 0;

-- **中断时刻**（票 03）：`status = 'interrupted'` 的行记下「什么时候断的」——排查断点时
-- 它要能与当时的系统状况（关机 / 崩溃）对上。其余行恒 NULL。
--
-- 这是对**决策 223「不做进程退出那一轮的落账」的显式修订**（spec .scratch/talk-replay
-- 决策 13）：进程退出的那一轮从此落一条**已中断**的半截行（而不是什么都不留）——
-- 半截轮终于有痕迹；「这一轮没跑起来」的失败账（`system` 行）仍照旧，两不相扰。
ALTER TABLE kanban_foreman_messages ADD COLUMN interrupted_at TEXT;
