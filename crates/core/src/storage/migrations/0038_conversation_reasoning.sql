-- 决策 360：流水线会话行的**推理 / 思考**留痕落库。
--
-- 为什么需要一列：决策 244 只给了 reasoning 两条去处——实时增量（`conversation_delta`
-- 的 `reasoning` 声道）与对讲台（`kanban_foreman_messages.thinking`，迁移 0025）。
-- 流水线节点的思考只有第一条去处，而实时流「能看一秒，然后永远看不到」——run 落地
-- （或页面刷新）的那一刻直播增量被台账接管，思考整段消失（迁移 0025 对值班长那侧
-- 的原话：比不展示更坏）。现场时间线（决策 349 / 359）把这条通道的会话整段搬上了
-- 界面，思考却始终缺席——用户 2026-10-01 报「没有把思考过程展示出来，至少需要把
-- 折叠的思考过程展示出来」就是这一列缺口的实机证据。
--
-- 三条口径（沿用迁移 0025 / 0017 的既有裁决，不另立新规）：
--   1. **它绝不回灌进模型上下文**（与 `content` 最要紧的区别，决策 244 原文照旧）：
--      推理段不是 assistant 消息的一部分，部分厂商把 `reasoning_content` 发回去会被拒；
--      进历史窗口还会让每轮白烧一份 token。它只被读出来展示（现场时间线的默认收起
--      思考步），永远不进 `messages_json` 的转录。
--   2. **多次调用的思考并成一列**：一次 run 的工具环可能有多轮调用，各轮的思考按
--      到达序以空行相连（谁先谁后就是发生序）。逐调用分步要靠与 assistant 消息的
--      对位账，那是另一笔工程；先让「想过的东西落地可见」。
--   3. **字符账独立成册**：`conversation_max_chars` 的三段共账（0017：系统段 → 用户段
--      → messages）不动——messages 在下一轮要重建，两段原文是「是不是 prompt 问题」
--      的根据，谁都不该被思考挤占。reasoning 是**展示留痕**（与 0025 的姿态相同），
--      单独按同一个上限截断且**留标记**，不许静默截短。
--
-- 可空：不产推理的模型、历史行与不走 LLM 的 run 这里是 NULL——NULL 就是「没有思考
-- 留痕」，界面不画一个空折叠块。

ALTER TABLE kanban_node_conversations ADD COLUMN reasoning TEXT;
