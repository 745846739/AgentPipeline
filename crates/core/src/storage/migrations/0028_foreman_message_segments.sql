-- 决策 273：值班长**一轮里的步骤顺序**留痕。
--
-- 为什么需要一列：此前一轮的三份留痕都是**聚合**视图——`thinking` 把各次调用的推理
-- 拼成一段、`traces_json` 把工具调用收成一张表、`content` 是收口那一句。三类各自都在，
-- 顺序却丢了：界面上看不出「先想了什么、再查了什么、然后说了什么」，而值班长的一轮
-- 常态正是「先想 → 查台账 → 再想 → 收口」。聚合列一列装不下顺序（把工具插回推理中间
-- 需要知道每次推理属于哪一次调用），故单开一列记**按发生顺序**的段序。
--
-- 形状：`[{"kind":"thinking","text":…}, {"kind":"tool","tool":…,"args_summary":…,"ok":…},
-- {"kind":"text","text":…}, …]`——由 `ForemanSegment` 序列化（内部标签 `kind`，
-- snake_case）。收口那一句是 `content` 列、不在段序里；没有工具但中途说过话的那些
-- 段序里也不会有它之外的 `text`。界面按它渲染时间线，不在前端二次拼装。
--
-- 与聚合列**并存**（决策 244 的 `thinking` / 票 05 的 `traces_json` 照旧保留）：聚合列
-- 各服务自己的消费者（折叠块 / 审计表），这一列服务顺序。
--
-- 可空：没有任何一步（不产推理、无工具、只收口一句）时这里是 NULL——与 `briefing_json`
-- / `traces_json` 同一条口径，「没有」与「有但是空的」是两件事。
ALTER TABLE kanban_foreman_messages ADD COLUMN segments_json TEXT;
