-- 决策 210① / 票 08：**任务级托管**。
--
-- 托管是**例外**，不是模式（决策 210①）：默认一切写动作照现状——环境层按 env_mode、
-- D 层恒提议。只有显式对**某个任务**打开托管，值班长才能对它免按键 `resume(continue)`。
--
-- 为什么不做全局档位（决策 210① 的原话）：一个全局开关一旦拨过去就再也回不来——
-- 你不会记得自己什么时候拨的、也不知道今晚它是开着的。任务级托管天然自限（任务一 done
-- 就失效），且与「一个任务 + N 次」的次数上限是同一个东西的两面。
--
-- 一列 JSON 装三件事（`enabled` / `auto_resumes` / `last_fingerprint`），不拆成三列：
-- 它们**同生同死**（打开托管时一起初始化、任务终态时一起失效），且每次读取都要一起读
-- （放行判据要「开着 + 没触顶 + 指纹不同」三条同时成立）。拆三列只会让「半边更新」
-- 成为可能——那正是这个开关最不该有的状态。
--
-- 保留期不另设：它跟任务行同生命周期（任务行怎么清，它就怎么清）。

ALTER TABLE kanban_tasks ADD COLUMN stewardship_json TEXT;
