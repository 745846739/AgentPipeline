-- 技能的**来源记录**（决策 194）：一个已装技能是从哪个仓的哪个 commit 的哪个子路径装来的。
--
-- 一行一个技能（`name` 是主键——技能名是唯一身份，决策 172）。
--
-- ## 为什么不往技能目录里写元数据文件
--
-- 技能目录里的任何文件都会进票 07 的**兄弟文件展开**——`skill_import::from_zip` 专门过滤
-- `__MACOSX` / `.DS_Store` 正是为了不让非技能内容混进去。我们自己的元数据文件是同一类噪声，
-- 而且比 `.DS_Store` 更坏：它会被当成"这个技能的兄弟文件"参与展开。
-- 故记**机器级事实**，记在库里（与迁移 0008 / 0009 那两张机器级单行表同族）。
--
-- ## 它承担三件事
--
-- 1. 同名冲突的报文要说清"将要覆盖的是哪个仓哪个版本"——而那三样（仓名、commit、子路径）
--    **一样都不在落盘路径里**，只能记；
-- 2. 一键安装的"本地已有同名 markdown 就跳过下载"那条分支要判定**已装的是不是清单指的那一份**
--    （决策 194 修订决策 181⑦）：判据是**仓 + 子路径**，**不比 commit**——清单是一个指针
--    （仓 + 目录），不是一份带版本的名录；而"和当前 tip 比"又要为此多发一次网络请求，正好
--    毁掉这条分支存在的理由（未配来源时也走得通）。跳过时**原样保留**记录里的 commit，
--    故既不静默换旧版，也不静默升级；
-- 3. 卸载要一并删记录（否则下一次同名安装的冲突报文会报一个已经不存在的技能曾经从哪儿来）。
--
-- **它不是安全判定**：放行与否只看 `owner/repo` 在不在仓名单里（`repo::repo_allowed`）。
-- 这张表是只读的记述，删掉它不影响任何放行判定。
--
-- 存完整 SHA 而不是短 SHA：短的那 7 位是从它截出来的**显示**形态，而这张表要记的是
-- "我装的是哪一份"的权威值（清单里的目录不带版本，装完那一刻的 tip 才是）。

CREATE TABLE IF NOT EXISTS skill_sources (
    name         TEXT PRIMARY KEY,
    owner        TEXT NOT NULL,
    repo         TEXT NOT NULL,
    commit_sha   TEXT NOT NULL,
    subpath      TEXT NOT NULL,
    installed_at TEXT NOT NULL
);
