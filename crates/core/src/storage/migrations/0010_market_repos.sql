-- 界面上的技能来源**仓名单**（决策 194；取代迁移 0009 的「来源 origin 白名单」，决策 187）。
--
-- 与 `kanban_server_bind`（迁移 0008）同构，理由也相同：**「有且只有一条记录」是不变式**
-- ——启动解析、界面保存、清除动作三处都假设它唯一，只靠「代码里记得别插第二行」维持的话，
-- 任何一次新增写入路径都可能悄悄破坏它（多出的一行不会被任何读取读到，表现为「改了没生效」
-- 这种极难定位的现象）。`CHECK (id = 1)` 让数据库自己拒绝第二行。
--
-- **为什么不写回 `config.toml` 的 `[market] github_repos`**：那个文件是手写配置
-- （注释即文档），写回必然要整体重排 TOML，用户的注释会静默消失；且本仓的边界由决策
-- 22 / 56 定下——**界面能改的配置不进 config.toml**。故界面改的那份住在这里，
-- `[market] github_repos` 仍是「声明式默认」：优先级「本表 > config.toml」，清掉本表即回到配置文件。
--
-- 存 JSON 数组原文而不是逗号分隔串：仓名本身不含逗号，但别为一个"今天成立"的假设定分隔符
-- ——迁移 0009 的注释里已经写过这条理由，JSON 也不引新依赖（serde_json 已在依赖里）。
--
-- **与 0009 的关系**：0009 那张表（`kanban_market_sources`）随决策 194 的整层替换而成为
-- **没人读的遗留表**。它的文件必须留着（`sqlx::migrate!` 对已应用的迁移记校验和，改动或删除
-- 会让既有库在启动时报版本不符——同决策 193 那条），但代码不再读写它。连表一起清掉是
-- **一条新迁移**（`DROP TABLE`）加一次显式的数据处置决定，不是这里的顺手事。

CREATE TABLE IF NOT EXISTS kanban_market_repos (
    id         INTEGER PRIMARY KEY CHECK (id = 1),
    repos_json TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
