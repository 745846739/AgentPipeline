-- 决策 294（票 foreman-unbounded 09）：提议**来路**的一个标记——「它来自一轮被按停的话」。
--
-- 为什么需要一列（而不是复用别处）：人按停那一轮提的悬空提议**不作废**（决策 294 显式修订
-- 233③：轮自己死了才作废，人主动停是「这话先这样，按你提的第 2 条办」），于是它们与正常
-- 收口那一轮提的提议在库里长得一模一样——而两者的可信度不同：前者的提议**提在一轮没说完
-- 的话里**，按之前值得多看一眼。这个差别只在这一刻知道，事后无从推出（题面里的判据要求
-- 「在提议上标注它来自一轮被停在半路的话」），故它必须落库。
--
-- 不复用 `situation_json`：那一列是态势**指纹**，参与 `situation_drift` 的逐值比对——往里
-- 塞一句人话会让「态势有没有漂」这件事永久为真，把漂移告警变成噪声。
-- 不改成新状态：钮必须照旧按得动（`pending` 是它的归宿），标记只是在旁边多一个读数。
--
-- NOT NULL DEFAULT 0 而不是可空：0 = 正常来路（绝大多数行），1 = 来自被人按停的那一轮——
-- 没有第三种，也不存在「不知道」。
ALTER TABLE kanban_foreman_proposals ADD COLUMN stopped_round INTEGER NOT NULL DEFAULT 0;
