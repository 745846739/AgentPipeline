-- 决策 292（票 foreman-unbounded 07）：值班长一轮的**成本界**——值守轮的生成 token 预算。
--
-- 为什么是 token 而不是墙钟 / 轮数（裁决 7）：一轮的真实成本 = 生成 token ÷ provider 吞吐，
-- 2026-09-26 那次实测 24 次调用生成 85,135 token、稳定 ~45 token/s，与上下文大小无关；
-- 墙钟杀的是「跑得久但一直在干活」（决策 288 已撤），轮数是模型行为失控的兜底。
-- 于是「能烧多少」成了唯一有意义的界。
--
-- **分档**（裁决 7）：值守轮有硬界（这条列，缺省 120k = 那次实测 85k 的约 1.4 倍，
-- 按 45 token/s ≈ 45 分钟）；人的那一轮**无硬界**——终点由人决定（人在看着本身就是那道
-- 界，票 09 的停钮是它的动作面），同一条线在人的那一轮上只落一条**软告警**（只落账不拦）。
--
-- 可空而不是 NOT NULL DEFAULT 120000：与 max_rounds（0024）同一条纪律——**缺省与「有人
-- 配过」要分得开**。NULL = 没配过（生效值是 120k），有人配过就落那个数；写入路径只收
-- **正整数**（`0` / 负数都不许，也没有「无预算」这一档——空值已经表达了「用缺省」，再给
-- 一个特殊值会让读的人要记两条例外）。
ALTER TABLE stage_configs ADD COLUMN watch_token_budget INTEGER;
