-- 「手机访问」页上的绑定开关（决策 186）：把「绑回环还是绑全网卡」这个选择持久化。
--
-- ## 为什么是「带 CHECK 的单行表」，而不是键值表或配置文件
--
-- 与 `kanban_pairing_token`（迁移 0007）同构：**「有且只有一条记录」是不变式**，不是
-- 应用层约定——启动解析、界面开关、清除动作三处都假设它唯一，唯一性只靠「代码里记得
-- 别插第二行」来维持的话，任何一次新增写入路径都可能悄悄破坏它（多出的一行不会被任何
-- 读取读到，表现为「开关点了没用」这种极难定位的现象）。`CHECK (id = 1)` 让数据库自己
-- 拒绝第二行。
--
-- **为什么不写回 `config.toml` 的 `[server] host`**：那个文件是手写配置（注释即文档），
-- 而写回必然要整体重排 TOML，用户的注释会静默消失。且本仓的边界是决策 22 / 56 定下的
-- ——**界面能改的配置不进 config.toml**。故界面改的那个值住在这里，`[server] host`
-- 仍是「声明式默认」，优先级：命令行 / 环境变量 > 本表 > `[server] host`（决策 186）。
--
-- `host` 存的是**显式绑定的地址原文**（`0.0.0.0` 或 `127.0.0.1`），不是布尔「开/关」：
-- 界面上的两颗钮就是这两种值，存原文让「将来允许绑某张网卡的 IP」不必改 schema。

CREATE TABLE IF NOT EXISTS kanban_server_bind (
    id         INTEGER PRIMARY KEY CHECK (id = 1),
    host       TEXT NOT NULL,
    updated_at TEXT NOT NULL
);
