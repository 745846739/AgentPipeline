-- 配对令牌（决策 182㉖㉗㉘，票 07）：局域网形态下写请求与工头端点的唯一凭据。
--
-- ## 为什么是「带 CHECK 的单行表」，而不是键值表或磁盘上的文件
--
-- 「有且只有一枚令牌」在本机制里是**不变式**，不是应用层约定：读取端点、校验中间件、
-- 重置端点三处都假设它唯一，而唯一性一旦只靠「代码里记得别插第二行」来维持，
-- 任何一次新增写入路径都可能悄悄破坏它（多出的一行不会被任何查询读到，表现为
-- 「重置后旧令牌仍然有效」这种极难定位的现象）。把 `id INTEGER PRIMARY KEY CHECK (id = 1)`
-- 写进 schema，就让数据库自己拒绝第二行——不变式由约束强制，而不是靠约定。
--
-- 键值表（key TEXT PRIMARY KEY, value TEXT）能装下，但它的通用性在这里没有消费者：
-- 本表只有一个键、一个值、一个时间戳，为不存在的扩展性付出「唯一性靠约定」的代价不划算。
-- 磁盘文件则要自己处理权限（0600）、原子替换、并发写与「文件丢失 ≠ 令牌失效」的语义，
-- 而 db 已由 Store 统一管住权限与事务（§12.14）；令牌与它要保护的写操作同库同事务，
-- 重置与校验不会出现「文件换了但数据库里还认为旧令牌有效」的中间态。

CREATE TABLE IF NOT EXISTS kanban_pairing_token (
    id         INTEGER PRIMARY KEY CHECK (id = 1),
    token      TEXT NOT NULL,
    created_at TEXT NOT NULL
);
