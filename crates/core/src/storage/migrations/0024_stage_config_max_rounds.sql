-- 决策 233① / 239：值班长一轮的**轮数上限**做成设置项，住 `stage_configs` 的 `foreman` 行。
--
-- 为什么是可空列而不是 NOT NULL DEFAULT 300：**缺省与「有人配过」要分得开**——NULL = 没配
-- （生效值是 300），有人配过就落那个数。写入路径只收**正整数**：`0` / 空 / `null` 都不许，
-- 也**不提供「无上限」**（决策 239 的两条理由：① 决策 224 已经拒过一次「无上限 + 重复调用
-- 告警」那条路；② 「0 = 无上限」会在配置面上造出**第二个「留空即特殊」的语义**——
-- 第一个是 `config set` 的「留空即清成默认」，两个特殊值叠在同一个字段上，读的人要记两条例外）。
--
-- 与墙钟的关系（决策 233 的如实记 (i)）：300 与 `respond` 的 timeout（缺省 1800s）是
-- **两条正交的界**，实际最坏值 `min(300 轮, 1800s)`——在 1800s 先到的情况下 300 不生效，
-- 抬墙钟另立一条。
ALTER TABLE stage_configs ADD COLUMN max_rounds INTEGER;
