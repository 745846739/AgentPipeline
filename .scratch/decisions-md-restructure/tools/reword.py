def main() -> None:
    from pathlib import Path
    src = Path("docs/decisions.md")
    text = src.read_text(encoding="utf-8")
    manifest: list[str] = ["# 措辞校正清单（票 01 提交 2）", ""]
    bad: list[str] = []
    for old, new, want in PAIRS:
        got = text.count(old)
        if got != want:
            bad.append(f"预期 {want} 次、实得 {got} 次：{old[:50]}…")
            continue
        text = text.replace(old, new)
        manifest.append(f"- 「{old}」→「{new}」×{want}")
    if bad:
        raise SystemExit("FAIL:\n" + "\n".join(bad))
    src.write_text(text, encoding="utf-8")

    readme = Path("docs/README.md")
    rtext = readme.read_text(encoding="utf-8")
    rold, rnew = "被修订时在行内标注", "被修订时在条目内标注"
    assert rtext.count(rold) == 1, "README 引用措辞未命中"
    readme.write_text(rtext.replace(rold, rnew), encoding="utf-8")
    manifest.append(f"- docs/README.md：「{rold}」→「{rnew}」×1")

    out = Path(__file__).resolve().parent.parent / "wording-manifest.md"
    out.write_text("\n".join(manifest) + "\n", encoding="utf-8")
    print(f"OK：{len(PAIRS) + 1} 处替换完成，清单落 {out.name}")


if __name__ == "__main__":
    main()
